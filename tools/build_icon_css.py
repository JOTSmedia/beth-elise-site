def moon_phase(lit, waxing):
    """Draw one lunar phase.

    `lit` is the illuminated fraction (0 new .. 1 full). Built from a half-disc
    plus a terminator ellipse, all clipped to the moon — an earlier version
    drew the limb and terminator as two arcs, but the sweep flags did not
    behave as expected and quarters came out mirrored, so this composes only
    rectangles and ellipses, where the result is unambiguous.
    """
    DARK, LIT = '%232A2247', 'url(%23mpg)'
    head = ('<defs>' + rad('mpg', '#FFF6D0', '#D9A63C', '40%', '30%', '78%') +
            '<clipPath id="mpc"><circle cx="34" cy="30" r="25"/></clipPath></defs>')
    rim = ('<circle cx="34" cy="30" r="25" fill="none" stroke="%23A97A00" '
           'stroke-width="1.3"/>')

    def craters(on_right):
        xs = [(41, 20, 3.4), (46, 35, 2.4), (37, 43, 1.8)]
        if not on_right:
            xs = [(68 - x, y, r) for x, y, r in xs]
        return ''.join(f'<circle cx="{x}" cy="{y}" r="{r}" fill="%23D9A63C" '
                       f'opacity=".38"/>' for x, y, r in xs)

    if lit <= 0.01:
        return head + f'<circle cx="34" cy="30" r="25" fill="{DARK}"/>' + rim
    if lit >= 0.99:
        return (head + f'<circle cx="34" cy="30" r="25" fill="{LIT}"/>' +
                craters(True) + rim)

    # lit half-disc on the leading limb: right while waxing, left while waning
    half_x = 34 if waxing else 9
    half = f'<rect x="{half_x}" y="5" width="25" height="50" fill="{LIT}"/>'
    # terminator: eats into the half for a crescent, spills past it for a gibbous
    rx = 25 * abs(1 - 2 * lit)
    term = (f'<ellipse cx="34" cy="30" rx="{rx:.1f}" ry="25" '
            f'fill="{DARK if lit < 0.5 else LIT}"/>')

    return (head +
            f'<g clip-path="url(%23mpc)">'
            f'<circle cx="34" cy="30" r="25" fill="{DARK}"/>{half}{term}'
            + (craters(waxing) if lit >= 0.5 else '') +
            '</g>' + rim)


for _key, _lit, _wax in [('new', 0.0, True), ('waxing-crescent', 0.25, True),
                         ('first-quarter', 0.5, True), ('waxing-gibbous', 0.75, True),
                         ('full', 1.0, True), ('waning-gibbous', 0.75, False),
                         ('last-quarter', 0.5, False), ('waning-crescent', 0.25, False)]:
    ICONS[f'moon-{_key}'] = moon_phase(_lit, _wax)


