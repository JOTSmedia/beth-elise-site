def _gear(teeth=8, r_out=28, r_in=21.5, hole=8.5, cx=34, cy=30):
    """Cog outline: four points per tooth so the tips come out flat, plus an
    even-odd hole so the centre reads as a bore rather than a dot."""
    import math
    T = 2 * math.pi / teeth
    w, g = T * 0.19, T * 0.11
    pts = []
    for i in range(teeth):
        a = i * T - math.pi / 2
        for r, ang in ((r_out, a - w), (r_out, a + w),
                       (r_in, a + w + g), (r_in, a + T - w - g)):
            pts.append(f'{cx + r * math.cos(ang):.1f} {cy + r * math.sin(ang):.1f}')
    ring = (f'M{cx - hole} {cy}'
            f'a{hole} {hole} 0 1 0 {hole * 2} 0'
            f'a{hole} {hole} 0 1 0 {-hole * 2} 0z')
    return 'M' + 'L'.join(pts) + 'z' + ring


